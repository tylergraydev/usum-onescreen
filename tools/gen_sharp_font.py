#!/usr/bin/env python3
"""Convert the vendored Apache-2.0 Roboto outline to bounded coverage data.

Requires Pillow 11.3.0 (FreeType 2.13.3), fonttools 4.61.1.
Run from any directory; --check verifies the checked-in generated include.
No proprietary font inputs are accepted.
"""
import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'tools/sharp-text/Roboto-Regular.ttf'
OUTPUT = ROOT / 'Sources/UI/SharpFont.inc'
# English UI literals and USUM English names: Pokémon/Flabébé, É in
# uppercased headings, curly apostrophes (Farfetch’d/Hau’oli), quotes/ellipsis
# in game dialogue. Other scripts and symbols deliberately use runtime CFNT.
CODEPOINTS = sorted(set(range(0x20, 0x7F)) | {0xC9, 0xE9, 0x2018, 0x2019,
                                            0x201C, 0x201D, 0x2026})


def generate():
    digest = hashlib.sha256(FONT.read_bytes()).hexdigest()
    if digest != '319cff6e7a31f0f2a41c475dca42890aa5d19fe16017e2290f8c1d4e14f76481':
        raise ValueError('Unexpected font input: use the vendored Roboto 2.137')
    face = ImageFont.truetype(str(FONT), 64, layout_engine=ImageFont.Layout.BASIC)
    data, entries = [], []
    cmap = TTFont(FONT).getBestCmap()
    for cp in CODEPOINTS:
        if cp not in cmap:
            raise ValueError(f'English subset missing U+{cp:04X}')
        box = face.getbbox(chr(cp))
        image = Image.new('L', (max(1, box[2]-box[0]), max(1, box[3]-box[1])))
        ImageDraw.Draw(image).text((-box[0], -box[1]), chr(cp), font=face, fill=255)
        image = image.point(lambda v: ((v + 8) // 17) * 17)
        ink = image.getbbox()
        if ink is None:
            continue  # spaces/format characters keep the runtime font path
        image = image.crop(ink)
        w, h = image.size
        if w > 255 or h > 255 or w * h > 4096:
            raise ValueError(f'U+{cp:04X} exceeds the existing cache slice')
        entries.append((cp, len(data), w, h))
        # Two coverage samples per byte, low nibble first. Each glyph starts
        # at a byte boundary; only its last high nibble can be padding.
        samples = [(v + 8) // 17 for v in image.tobytes()]
        for i in range(0, len(samples), 2):
            data.append(samples[i] | ((samples[i+1] if i+1 < len(samples) else 0) << 4))
    if len(data) > 65535:
        raise ValueError('English coverage exceeds the 16-bit offset budget')
    lines = [
        '// Generated by tools/gen_sharp_font.py. Do not edit.',
        '// SharpText coverage derived from Roboto Regular 2.137, 64 px.',
        '// Copyright 2011 Google Inc. All Rights Reserved. Apache-2.0.',
        '// English subset, tightly cropped packed A4; see tools/sharp-text/LICENSE.txt.',
        f'// Input SHA-256: {digest}',
        'static const u8 s_sharpData[] = {',
    ]
    for i in range(0, len(data), 24):
        lines.append('    ' + ','.join(f'0x{v:02x}' for v in data[i:i+24]) + ',')
    lines += ['};', 'struct SharpEntry { u16 cp, offset; u8 w, h; };',
              'static_assert(sizeof(SharpEntry) == 6, "SharpText index memory budget");',
              'static const SharpEntry s_sharpEntries[] = {']
    lines += [f'    {{0x{cp:x}, {offset}, {w}, {h}}},' for cp, offset, w, h in entries]
    lines += ['};', 'static_assert(sizeof(s_sharpData) + sizeof(s_sharpEntries) + 96 <= 80 * 1024,',
              '              "SharpText total static data exceeds 80 KiB");', '']
    print(f'{len(entries)} glyphs, {len(data)} packed A4 bytes, '
          f'{len(entries)*6} table bytes, 96 cache metadata bytes, '
          f'{len(data)+len(entries)*6+96} total static bytes; no decoded static scratch')
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != result:
            raise SystemExit('SharpFont.inc differs; regenerate with the pinned tool versions')
        print('SharpFont.inc matches')
    else:
        OUTPUT.write_text(result, encoding='utf-8', newline='\n')
