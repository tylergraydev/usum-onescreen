"""Generate Includes/Layouts.hpp from layouts/usum-v1.2.json.

    py -3 -I tools/gen_layouts.py            # rewrite the header
    py -3 -I tools/gen_layouts.py --check    # exit 1 if the header is out of date (tests/ runs this)

The plugin has no JSON parser and the layouts only change when someone
re-measures them, so they are compiled in: one table row per button that has a
tap point, named "screen.button" as in the JSON.
"""

import argparse
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
JSON_PATH = REPO / "layouts" / "usum-v1.2.json"
HEADER_PATH = REPO / "Includes" / "Layouts.hpp"

VERIFIED = {"tap": "LayoutVerified::Tap", "measured": "LayoutVerified::Measured", "none": "LayoutVerified::None"}


def generate(data):
    rows = []
    for screen, body in data["screens"].items():
        for name, button in body["buttons"].items():
            tap = button.get("tap")
            if tap is None:
                continue
            rect = button.get("rect") or [-1, -1, -1, -1]
            verified = VERIFIED[button["verified"]]
            rows.append(f'        {{ "{screen}.{name}", {rect[0]}, {rect[1]}, {rect[2]}, {rect[3]}, '
                        f'{tap[0]}, {tap[1]}, {verified} }},')

    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/gen_layouts.py from layouts/usum-v1.2.json; do not edit.",
        "// Bottom-screen buttons of Ultra Sun v1.2 (docs/LAYOUTS.md): rect is",
        "// x0, y0, x1, y1 inclusive (-1 if none), tap is the point that was tested.",
        "",
        "#include <cstdint>",
        "",
        "namespace OneScreen",
        "{",
        "    // tap: a tap there did what the JSON says; measured: deliberately never",
        "    // tapped (would change the game); none: a tap does nothing.",
        "    enum class LayoutVerified : uint8_t { Tap, Measured, None };",
        "",
        "    struct LayoutButton",
        "    {",
        "        const char *name;   // \"screen.button\"",
        "        int16_t x0, y0, x1, y1;",
        "        int16_t tapX, tapY;",
        "        LayoutVerified verified;",
        "    };",
        "",
        "    static const LayoutButton LayoutButtons[] =",
        "    {",
        *rows,
        "    };",
        "",
        "    static const unsigned LayoutButtonCount = sizeof(LayoutButtons) / sizeof(LayoutButtons[0]);",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only compare with the committed header")
    args = parser.parse_args()

    text = generate(json.loads(JSON_PATH.read_text(encoding="utf-8")))
    if args.check:
        current = HEADER_PATH.read_text(encoding="utf-8") if HEADER_PATH.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{HEADER_PATH.relative_to(REPO)} is out of date: run py -3 -I tools/gen_layouts.py")
            return 1
        print(f"{HEADER_PATH.relative_to(REPO)} matches {JSON_PATH.relative_to(REPO)}")
        return 0
    HEADER_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {HEADER_PATH.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
